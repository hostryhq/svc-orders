// Command gen reads api-specs and writes the generated tables of svc-orders (run by `make gen`;
// the output is committed and never edited):
//
//	api/policy_gen.go          route table: operationId, x-permission, x-service-callers
//	service/catalogue_gen.go   the permission catalogue
//	service/entities/*.yaml    the entity files orders owns (ADR-0014 R1) or holds as declared read-only
//	                           replicas (replicated_to: orders, A2.4), copied verbatim; the go-common/sync
//	                           registry is loaded from them (docs/notes.md N2, N3)
//	events/subscriptions_gen.go  sync op namespaces orders subscribes to (ADR-0011 B10)
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

func main() {
	specs := flag.String("specs", "", "api-specs checkout")
	commit := flag.String("commit", "unknown", "api-specs commit")
	flag.Parse()
	if *specs == "" {
		log.Fatal("gen: -specs is required")
	}
	must(genPolicies(filepath.Join(*specs, "build/orders.yaml"), *commit))
	must(genCatalogue(filepath.Join(*specs, "common/permissions.yaml"), *commit))
	owned := genEntities(filepath.Join(*specs, "entities/restaurant"), *commit)
	must(genSubscriptions(filepath.Join(*specs, "sync/intents"), owned, *commit))
}

func must(err error) {
	if err != nil {
		log.Fatal(err)
	}
}

func genPolicies(specPath, commit string) error {
	raw, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}
	var d struct {
		Paths map[string]map[string]map[string]any `yaml:"paths"`
	}
	if err := yaml.Unmarshal(raw, &d); err != nil {
		return err
	}
	type row struct {
		pattern, op, perm string
		outlet            bool
		callers           []string
	}
	var rows []row
	for path, item := range d.Paths {
		for m, op := range item {
			switch m {
			case "get", "post", "put", "patch", "delete":
			default:
				continue
			}
			r := row{pattern: strings.ToUpper(m) + " " + path, op: str(op["operationId"]), perm: str(op["x-permission"])}
			r.outlet, _ = op["x-outlet-scoped"].(bool)
			if cs, ok := op["x-service-callers"].([]any); ok {
				for _, c := range cs {
					r.callers = append(r.callers, str(c))
				}
			}
			if r.op == "" || r.perm == "" {
				return fmt.Errorf("gen: %s has no operationId or x-permission", r.pattern)
			}
			rows = append(rows, r)
		}
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].pattern < rows[j].pattern })
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/gen from api-specs %s; DO NOT EDIT.\n\npackage api\n\n", commit)
	fmt.Fprintf(&b, "// APISpecsCommit is the api-specs commit this table was generated from.\nconst APISpecsCommit = %q\n\n", commit)
	b.WriteString("var routeTable = []routeSpec{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t{Pattern: %q, Op: %q, Permission: %q, OutletScoped: %v, Callers: %#v},\n", r.pattern, r.op, r.perm, r.outlet, r.callers)
	}
	b.WriteString("}\n")
	return write("api/policy_gen.go", b.Bytes())
}

func genCatalogue(path, commit string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var d struct {
		Version int `yaml:"catalogue_version"`
		Perms   []struct {
			Key, Realm, Service string
			Flags               []string `yaml:"flags"`
		} `yaml:"permissions"`
	}
	if err := yaml.Unmarshal(raw, &d); err != nil {
		return err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/gen from api-specs %s common/permissions.yaml; DO NOT EDIT.\n\npackage service\n\n", commit)
	fmt.Fprintf(&b, "// CatalogueVersion is the catalogue_version of the permission catalogue.\nconst CatalogueVersion = %d\n\n", d.Version)
	b.WriteString("var catalogueEntries = []catalogueEntry{\n")
	for _, p := range d.Perms {
		has := func(f string) bool {
			for _, x := range p.Flags {
				if x == f {
					return true
				}
			}
			return false
		}
		fmt.Fprintf(&b, "\t{Key: %q, Realm: %q, Service: %q, Sensitive: %v, StrongOnly: %v, SupportViewable: %v, SupportActable: %v, OwnerGrant: %v},\n",
			p.Key, p.Realm, p.Service, has("sensitive"), has("strong_only"), has("support_viewable"), has("support_actable"), has("owner_grant"))
	}
	b.WriteString("}\n")
	return write("service/catalogue_gen.go", b.Bytes())
}

// genEntities copies every entity file orders owns or replicates (owner: orders, or replicated_to
// naming orders) into service/entities, verbatim behind a one-line header, and returns their names.
func genEntities(dir, commit string) map[string]bool {
	files, err := filepath.Glob(filepath.Join(dir, "*.yaml"))
	must(err)
	out := "service/entities"
	must(os.RemoveAll(out))
	must(os.MkdirAll(out, 0o755))
	names := map[string]bool{}
	for _, f := range files {
		raw, err := os.ReadFile(f)
		must(err)
		var e struct {
			Entity       string `yaml:"entity"`
			Owner        string `yaml:"owner"`
			ReplicatedTo []struct {
				Service string `yaml:"service"`
			} `yaml:"replicated_to"`
		}
		must(yaml.Unmarshal(raw, &e))
		mine := e.Owner == "orders"
		for _, r := range e.ReplicatedTo {
			mine = mine || r.Service == "orders"
		}
		if !mine {
			continue
		}
		names[e.Entity] = true
		hdr := fmt.Sprintf("# Copied by cmd/gen from api-specs %s entities/restaurant/%s; DO NOT EDIT.\n", commit, filepath.Base(f))
		must(os.WriteFile(filepath.Join(out, filepath.Base(f)), append([]byte(hdr), raw...), 0o644))
	}
	return names
}

func genSubscriptions(dir string, owned map[string]bool, commit string) error {
	files, err := filepath.Glob(filepath.Join(dir, "*.yaml"))
	if err != nil || len(files) == 0 {
		return fmt.Errorf("gen: no intent registry in %s (sync/intents is needed for the bus subscriptions)", dir)
	}
	ns := map[string]bool{"sync": true} // sync.void reaches every projection
	for _, f := range files {
		raw, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		var d struct {
			Intents []struct {
				Intent   string                 `yaml:"intent"`
				Entities map[string]interface{} `yaml:"entities"`
			} `yaml:"intents"`
		}
		if err := yaml.Unmarshal(raw, &d); err != nil {
			return err
		}
		for _, in := range d.Intents {
			for e := range in.Entities {
				if owned[e] {
					ns[strings.SplitN(in.Intent, ".", 2)[0]] = true
				}
			}
		}
	}
	names := make([]string, 0, len(ns))
	for n := range ns {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/gen from api-specs %s sync/intents; DO NOT EDIT.\n\npackage events\n\n", commit)
	b.WriteString("// SyncNamespaces are the intent namespaces whose ops can touch an entity orders projects; the durable\n// consumer of orders is filtered to evt.sync.op.<namespace>.v1 for each (ADR-0011 B6, B10).\n")
	fmt.Fprintf(&b, "var SyncNamespaces = %#v\n", names)
	return write("events/subscriptions_gen.go", b.Bytes())
}

func write(path string, src []byte) error {
	out, err := format.Source(src)
	if err != nil {
		return fmt.Errorf("gen: %s: %w", path, err)
	}
	return os.WriteFile(path, out, 0o644)
}

func str(v any) string {
	s, _ := v.(string)
	return s
}
